    public function run(): void
    {
        $owner = User::where('role', User::ROLE_ADMIN)->first()
            ?? User::first();

        if (! $owner) {
            $owner = User::create([
                'name' => 'Admin Coworking SP',
                'email' => DatabaseSeeder::ADMIN_EMAIL,
                'password' => DatabaseSeeder::PASSWORD,
            ]);
            $owner->forceFill(['role' => User::ROLE_ADMIN])->save();
        }

        foreach (self::COMPANIES as $item) {
            $schedule = $this->buildSchedule($item['days'], $item['from'], $item['to']);

            Space::firstOrCreate(
                [
                    'name' => $item['name'],
                    'city' => $item['city'],
                    'state' => $item['state'],
                ],
                [
                    'user_id' => $owner->id,
                    'description' => $item['description'],
                    'capacity' => $item['capacity'],
                    'zip_code' => $item['zip_code'],
                    'street' => $item['street'],
                    'number' => $item['number'],
                    'complement' => $item['complement'],
                    'neighborhood' => $item['neighborhood'],
                    'latitude' => $item['latitude'],
                    'longitude' => $item['longitude'],
                    'hourly_price' => $item['hourly_price'],
                    'daily_price' => $item['daily_price'],
                    'monthly_price' => $item['monthly_price'],
                    'is_free' => $item['is_free'],
                    'opening_hours' => $schedule,
                    'availability' => $schedule,
                    'amenities' => $item['amenities'],
                    'is_active' => true,
                ],
            );
        }
    }

    private function buildSchedule(array $enabledDays, string $from, string $to): array
    {
        return array_map(
            fn (int $day) => [
                'day' => $day,
                'enabled' => in_array($day, $enabledDays, true),
                'from' => $from,
                'to' => $to,
            ],
            range(0, 6),
        );
    }
